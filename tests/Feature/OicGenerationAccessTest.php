<?php

use App\Livewire\Documents\{CreateDocument, ViewDocument};
use App\Models\{Document, DocumentGenerationRule, DocumentType, ExternalDocument, Office, Permission, Role, User};
use App\Services\DocumentGenerationService;
use Livewire\Livewire;

beforeEach(function () {
    $role = Role::create(['role' => 'sao-oic-generation', 'description' => 'SAO']);
    $role->permissions()->attach(Permission::whereIn('key', ['send_documents', 'receive_documents', 'send_external_documents'])->pluck('id'));
    $this->office = Office::create(['name' => 'SAO Administration', 'abbreviation' => 'SAO', 'office_type' => 'ADMIN']);
    $this->head = User::factory()->create(['office_id' => $this->office->id, 'role_id' => $role->id]);
    $this->oic = User::factory()->create(['office_id' => $this->office->id]);
    $this->office->update(['head_id' => $this->head->id]);
    $sourceType = DocumentType::create(['name' => 'Request', 'abbreviation' => 'RLM']);
    $this->target = DocumentType::create(['name' => 'Generated memo', 'abbreviation' => 'IOM', 'recipient_mode' => 'none', 'requires_signatories' => false, 'is_publicly_creatable' => true]);
    $this->document = Document::create(['document_number' => 'RLM-OIC-1', 'from_id' => $this->office->id, 'document_type_id' => $sourceType->id, 'created_by' => $this->head->id, 'subject' => 'Approved request', 'content' => 'Body', 'status' => 'Approved']);
    $this->document->steps()->create(['office_id' => $this->office->id, 'user_id' => $this->head->id, 'step_type' => 'action', 'step_label' => 'Generate IOM', 'sequence' => 1, 'status' => 'Pending']);
    $this->rule = DocumentGenerationRule::create(['source_context' => 'internal', 'source_document_type_id' => $sourceType->id, 'target_document_type_id' => $this->target->id, 'button_label' => 'Generate IOM', 'required_status' => 'Approved', 'requires_assigned_office' => false]);
    $this->rule->roles()->attach($role->id);
});

it('keeps the head able to view while only the OIC can generate even for an unrestricted rule', function () {
    $this->office->update(['acting_head_id' => $this->oic->id]);
    $this->actingAs($this->head);
    Livewire::test(ViewDocument::class, ['number' => $this->document->document_number])
        ->assertStatus(200)->assertSet('generationRules', [])->assertSet('canAct', false)
        ->assertSee('You can view this document, but only your assigned OIC can take action while acting on your behalf.')
        ->call('generateDocument', $this->rule->id)->assertForbidden();
    $this->actingAs($this->oic);
    Livewire::test(ViewDocument::class, ['number' => $this->document->document_number])
        ->assertSee('Generate IOM')->assertDontSee('only your assigned OIC can take action')->call('generateDocument', $this->rule->id)
        ->assertRedirect(route('documents.create-document'));
    Livewire::test(CreateDocument::class)->set('content', 'Generated by OIC')->call('submitDocument', 'send')->assertHasNoErrors();
    $generated = Document::where('document_type_id', $this->target->id)->firstOrFail();
    expect($generated->created_by)->toBe($this->oic->id);
    $step = $this->document->steps()->where('step_type', 'action')->firstOrFail();
    expect($step->status)->toBe('Approved');
    expect($step->processed_at)->not->toBeNull();
    expect($step->user_id)->toBe($this->oic->id);
    expect($step->comments)->toContain($generated->document_number);
});

it('blocks a generation form opened before the OIC appointment', function () {
    $this->actingAs($this->head);
    session()->flash('redirect_data', app(DocumentGenerationService::class)->redirectData($this->rule, $this->document, $this->head));
    $form = Livewire::test(CreateDocument::class)->set('content', 'Prepared before OIC');
    $this->office->update(['acting_head_id' => $this->oic->id]);
    $form->call('submitDocument', 'Draft')->assertHasErrors('document_type_id');
    expect(Document::where('document_type_id', $this->target->id)->exists())->toBeFalse();
});

it('blocks external generation for the relieved head and restores access after OIC removal', function () {
    $external = ExternalDocument::create(['document_number' => 'EXT-OIC-1', 'from' => 'Agency', 'to_id' => $this->office->id, 'subject' => 'External request', 'received_date' => now(), 'file_url' => 'test.pdf', 'file_type' => 'pdf']);
    $rule = DocumentGenerationRule::create(['source_context' => 'external', 'target_document_type_id' => $this->target->id, 'button_label' => 'Generate reply', 'requires_assigned_office' => false]);
    $rule->roles()->attach($this->head->role_id);
    $this->office->update(['acting_head_id' => $this->oic->id]);
    $service = app(DocumentGenerationService::class);
    expect($service->availableForExternal($external, $this->head))->toBeEmpty();
    expect($service->availableForExternal($external, $this->oic))->toHaveCount(1);
    $this->office->update(['acting_head_id' => null]);
    expect($service->availableForInternal($this->document, $this->head))->toHaveCount(1);
    expect($service->availableForExternal($external, $this->head))->toHaveCount(1);
});


it('does not show the OIC notice when no OIC is appointed', function () {
    $this->actingAs($this->head);
    Livewire::test(ViewDocument::class, ['number' => $this->document->document_number])
        ->assertSet('oicViewOnly', false)->assertDontSee('only your assigned OIC can take action')
        ->assertSee('Generate IOM');
});


it('keeps generated sources visible as read-only history for the head and OIC', function (string $stepStatus) {
    $this->office->update(['acting_head_id' => $this->oic->id]);
    $this->document->update(['status' => 'Generated IOM']);
    $this->document->steps()->update(['status' => $stepStatus]);
    // Even a rule without a required status must not allow repeat generation.
    $this->rule->update(['required_status' => null]);
    $queries = app(\App\Services\DocumentQueryService::class);
    foreach ([$this->head, $this->oic] as $user) {
        expect($queries->canView($user, $this->document->document_number))->toBeTrue();
        expect($queries->listFor($user, 'received')->whereKey($this->document->id)->exists())->toBeTrue();
        $this->actingAs($user);
        Livewire::test(ViewDocument::class, ['number' => $this->document->document_number])
            ->assertStatus(200)->assertSet('canAct', false)->assertSet('canGenerate', false)
            ->assertDontSee('wire:click="sign"', false)->assertDontSee('wire:click="reject"', false)
            ->assertDontSee('wire:click="generateDocument(', false);
        foreach (['sign', 'reject', 'lastStep'] as $action) {
            Livewire::test(ViewDocument::class, ['number' => $this->document->document_number])
                ->call($action)->assertForbidden();
        }
        Livewire::test(ViewDocument::class, ['number' => $this->document->document_number])
            ->call('generateDocument', $this->rule->id)->assertForbidden();
    }
    $unrelatedOffice = Office::create(['name' => 'Unrelated', 'abbreviation' => 'UNR', 'office_type' => 'ADMIN']);
    $unrelated = User::factory()->create(['office_id' => $unrelatedOffice->id, 'role_id' => $this->head->role_id]);
    expect($queries->canView($unrelated, $this->document->document_number))->toBeFalse();
    expect($this->document->fresh()->status)->toBe('Generated IOM');
})->with(['legacy pending action' => ['Pending'], 'completed action' => ['Approved']]);

it('blocks a stale generation form after its source becomes generated', function () {
    $this->office->update(['acting_head_id' => $this->oic->id]);
    $this->rule->update(['required_status' => null]);
    $this->actingAs($this->oic);
    session()->flash('redirect_data', app(DocumentGenerationService::class)->redirectData($this->rule, $this->document, $this->oic));
    $form = Livewire::test(CreateDocument::class)->set('content', 'Response');
    $this->document->update(['status' => 'Generated IOM']);
    $form->call('submitDocument', 'Draft')->assertHasErrors('document_type_id');
    expect(Document::where('document_type_id', $this->target->id)->exists())->toBeFalse();
});


it('completes the generation step when a permitted generator differs from the assigned person', function () {
    $otherOffice = Office::create(['name' => 'Assigned generation office', 'abbreviation' => 'AGO', 'office_type' => 'ADMIN']);
    $assignee = User::factory()->create(['office_id' => $otherOffice->id]);
    $otherOffice->update(['head_id' => $assignee->id]);
    $this->document->steps()->update(['office_id' => $otherOffice->id, 'user_id' => $assignee->id, 'assigned_user_id' => $assignee->id]);
    $this->actingAs($this->head);
    session()->flash('redirect_data', app(DocumentGenerationService::class)->redirectData($this->rule, $this->document, $this->head));
    Livewire::test(CreateDocument::class)->set('content', 'Generated IOM')->call('submitDocument', 'send')->assertHasNoErrors();
    $step = $this->document->steps()->where('step_type', 'action')->firstOrFail();
    expect($this->document->fresh()->status)->toBe('Generated IOM');
    expect($step->status)->toBe('Approved');
    expect($step->processed_at)->not->toBeNull();
    expect($step->user_id)->toBe($this->head->id);
    expect($step->assigned_user_id)->toBe($assignee->id);
});

it('does not complete generation when only a draft is saved', function () {
    $this->actingAs($this->head);
    session()->flash('redirect_data', app(DocumentGenerationService::class)->redirectData($this->rule, $this->document, $this->head));
    Livewire::test(CreateDocument::class)->set('content', 'Draft IOM')->call('submitDocument', 'Draft')->assertHasNoErrors();
    $step = $this->document->steps()->where('step_type', 'action')->firstOrFail();
    expect($step->status)->toBe('Pending');
    expect($step->processed_at)->toBeNull();
    expect($this->document->fresh()->status)->toBe('Approved');
});
